"""Summarize fresh-process measurements without pooling unlike workloads."""

from collections import defaultdict
import json
from pathlib import Path
from statistics import median

root=Path(__file__).resolve().parent
records=[json.loads(line) for line in (root/'results-validated.jsonl').read_text().splitlines()]
groups=defaultdict(list)
for row in records:
    case={k:v for k,v in row['case'].items() if k!='replicate'}
    groups[json.dumps(case,sort_keys=True)].append(row)

summary=[]
for key,rows in sorted(groups.items()):
    times=[median(r['seconds'])*1000 for r in rows]
    rss=[r['peak_rss_bytes']/2**20 for r in rows]
    trace=[r['whole_trace']['peak_bytes']/2**20 for r in rows]
    summary.append(dict(case=json.loads(key),replicates=len(rows),
        ms=median(times),ms_min=min(times),ms_max=max(times),
        rss_mib=median(rss),rss_min=min(rss),rss_max=max(rss),
        trace_mib=median(trace),trace_min=min(trace),trace_max=max(trace),
        max_abs_difference=max(r['max_abs_difference'] for r in rows),
        tolerance_pass=all(r.get('tolerance_pass',True) for r in rows),
        tolerance_violations=max(r.get('tolerance_violations',0) for r in rows)))
(root/'summary.json').write_text(json.dumps(summary,indent=2))

lines=['# Complete benchmark matrix','','Last updated on: 2026-09-16','',
       'Generated by `summarize.py` from `results-validated.jsonl`. Milliseconds and RSS are medians of three fresh processes; each process contributes its median of warm calls. Ranges span the three process medians (time) or process peaks (RSS). Traced temporary peaks exclude persistent arrays created before tracing. The report explains workload and measurement limits. `native` means Boolean for binary selections and float32 for mixed selections. Each variant appears separately so results are not selected by apparent benefit.','',
       '| Case | Operator | Contributors | Outputs/block | Width | Reuses | Binary density | Continuous fraction/source | Variant | ms (range) | Peak RSS MiB (range) | Temporary trace MiB | Error vs explicit | Tolerance pass |',
       '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- | ---: | ---: | ---: | ---: | --- |']
for s in summary:
    c=s['case']
    density=1 if c['operator']=='dense' else c['density']
    lines.append(f"| {c['name']} | {c['operator']} ({density:g}) | {c['n']} | {c['m']} | {c['q']} | {c.get('blocks','actual tiling')} | {c.get('annotation_density',.1):g} | {c.get('source',c.get('continuous_fraction',0))} | {c['variant']} | {s['ms']:.3f} ({s['ms_min']:.3f}–{s['ms_max']:.3f}) | {s['rss_mib']:.2f} ({s['rss_min']:.2f}–{s['rss_max']:.2f}) | {s['trace_mib']:.3f} | {s['max_abs_difference']:.3g} | {s['tolerance_pass']} |")
(root/'MATRIX.md').write_text('\n'.join(lines)+'\n')
print('processes',len(records),'groups',len(summary),'subprocess seconds',sum(r['subprocess_seconds'] for r in records))
print('tolerance failures',[(s['case'],s['tolerance_violations'],s['max_abs_difference']) for s in summary if not s['tolerance_pass']])
for s in summary:
    if s['case']['suite']=='projection':
        print(s['case'],{k:round(s[k],3) for k in ('ms','rss_mib','rss_min','rss_max','trace_mib')})
